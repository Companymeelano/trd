/* ---------------------------------------------------------------------------
   0) Guard rails
   --------------------------------------------------------------------------- */
IF N'$(SqlLoginPassword)' = N'' OR N'$(SqlLoginPassword)' LIKE N'%paste strong%'
BEGIN
    RAISERROR('Aborted: pass the password with sqlcmd -v SqlLoginPassword="..." (do not edit this file).', 16, 1);
END
GO

/* ---------------------------------------------------------------------------
   1) Server login (dynamic SQL so the password never appears in this script)
   --------------------------------------------------------------------------- */
BEGIN TRY
    DECLARE @pwd  nvarchar(256) = N'$(SqlLoginPassword)';
    DECLARE @sql  nvarchar(max);

    IF NOT EXISTS (SELECT 1 FROM sys.server_principals WHERE name = N'vizitor_app')
    BEGIN
        SET @sql = N'CREATE LOGIN [vizitor_app] WITH PASSWORD = N'''
                 + REPLACE(@pwd, '''', '''''')
                 + N''', CHECK_POLICY = ON, CHECK_EXPIRATION = OFF, DEFAULT_DATABASE = [Atiran2];';
        EXEC sp_executesql @sql;
        PRINT 'LOGIN [vizitor_app] created.';
    END
    ELSE
        PRINT 'LOGIN [vizitor_app] already exists - password NOT changed by this script.';

    SET @pwd = N'';   /* clear from memory as early as possible */
END TRY
BEGIN CATCH
    PRINT 'Login step failed: ' + ERROR_MESSAGE();
END CATCH
GO

