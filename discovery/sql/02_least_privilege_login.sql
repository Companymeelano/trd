/* ---------------------------------------------------------------------------
   6) DENY the dangerous surface (defence in depth for a credential that lives
      inside a decompilable APK)

      Database-scope denies (safe to run here):
   --------------------------------------------------------------------------- */
BEGIN TRY
    /* Stops the app login from reading the bodies of procedures it does not own.
       Remove this line while you are still debugging, re-add it for production. */
    DENY VIEW DEFINITION TO [vizitor_app];
    /* No schema changes, ever. */
    DENY ALTER ON SCHEMA::[dbo] TO [vizitor_app];
    DENY CREATE TABLE     TO [vizitor_app];
    DENY CREATE VIEW      TO [vizitor_app];
    DENY CREATE PROCEDURE TO [vizitor_app];
    DENY CREATE FUNCTION  TO [vizitor_app];
    DENY CREATE TRIGGER   TO [vizitor_app];
