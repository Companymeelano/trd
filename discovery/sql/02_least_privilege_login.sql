/* ---------------------------------------------------------------------------
   7) Verification - run as the new login afterwards and confirm the app's
      real queries succeed and everything else fails
   --------------------------------------------------------------------------- */
PRINT '';
PRINT 'Grants now in place for vizitor_app:';
SELECT
    dp.name              AS Grantee,
    perm.permission_name AS Permission,
    perm.state_desc      AS State,
    SCHEMA_NAME(o.schema_id) + '.' + o.name AS OnObject
FROM sys.database_permissions perm
JOIN sys.database_principals dp ON dp.principal_id = perm.grantee_principal_id
LEFT JOIN sys.objects o         ON o.object_id = perm.major_id
WHERE dp.name IN ('vizitor_app','vizitor_reader','vizitor_writer')
ORDER BY OnObject, perm.permission_name;
GO

/* =====================================================================================
   SERVER / NETWORK CONFIGURATION (do these in SQL Server Configuration Manager +
   Windows Firewall - they cannot be expressed in T-SQL):

   1. SQL Server Network Configuration -> Protocols -> TCP/IP = Enabled
      -> IPAll: TCP Port = 1433, TCP Dynamic Ports = (empty)   [named instances otherwise
         use a dynamic port and the phone would need SQL Browser / UDP 1434]
   2. SQL Server Properties -> Security -> "SQL Server and Windows Authentication mode"
   3. SQL Server Properties -> Connections -> "Allow remote connections to this server"
   4. Force Encryption: SQL Server Network Configuration -> right-click Protocols ->
      Properties -> Force Encryption = Yes  (requires a valid certificate; strongly
      recommended - see the driver/TLS notes in the migration plan)
   5. Windows Firewall (inbound, restricted to the visitor subnet/VPN only):
         New-NetFirewallRule -DisplayName "SQL Server 1433 (Vizitor)" `
           -Direction Inbound -Protocol TCP -LocalPort 1433 -Action Allow `
           -RemoteAddress <VPN_or_LAN_subnet>      # never 0.0.0.0/0
         New-NetFirewallRule -DisplayName "SQL Browser UDP 1434" -Direction Inbound `
           -Protocol UDP -LocalPort 1434 -Action Allow -RemoteAddress <VPN_or_LAN_subnet>
      (Only needed for named instances; prefer a fixed TCP port and keep UDP closed.)
   ===================================================================================== */
